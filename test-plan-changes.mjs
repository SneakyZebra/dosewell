import assert from 'node:assert/strict';
import {revisePlan,scheduledPlans} from './plan-changes.js';
import {dosesFor,dueEvents,calendarFile} from './schedule.js';
import {logDose,logAsNeeded,lastTaken,recordedStatus} from './dose-log.js';
import {exportBackup,readBackup} from './plan-backup.js';

const day='2026-11-08', next='2026-11-09';
const med={id:'abc',name:'Test medication',category:'other',mode:'daily',start:day,end:'',times:['08:00','18:00'],days:[0,1,2,3,4,5,6],dose:'Test dose',advance:null};
const state={version:1,meds:[med],history:{},taken:{},snoozes:{},fired:{},supplies:{},settings:{advance:15,notifications:false,sound:true,handoff:true},profile:{name:'Example',allergies:'Entered by patient',reviewed:day}};
const at=t=>new Date(day+'T'+t+':00');
const key='abc|'+day+'|08:00';
logDose(state,key,'taken',at('08:30'),{takenAt:+at('08:05'),by:'Test caregiver'});
const newMed={...med,times:['09:00','19:00']};
assert.throws(()=>revisePlan(state,med,newMed,day,day),/confirm/);
assert.throws(()=>revisePlan(state,med,newMed,day,day,'08:00',true,at('08:30')),/future/);
state.meds=[revisePlan(state,med,newMed,next,day)];
assert.deepEqual(dosesFor(state.meds,day).map(r=>r.time),med.times);
assert.deepEqual(dosesFor(state.meds,next).map(r=>r.time),newMed.times);
assert.equal(recordedStatus(state,key),'taken');
assert.deepEqual(dueEvents(state,at('09:00'),+at('08:59')),[]);
assert.match(calendarFile(state,at('08:30')).text,/20261109T090000/);
assert.doesNotMatch(calendarFile(state,at('08:30')).text,/20261108T090000/);
const immediate=revisePlan(state,med,newMed,day,day,'12:00',true,at('08:30'));
assert.deepEqual(dosesFor([immediate],day).map(r=>r.time),['08:00','19:00']);
assert.deepEqual(dosesFor([immediate],next).map(r=>r.time),newMed.times);
assert.equal(lastTaken(state,'abc').takenAt,+at('08:05'));
assert.throws(()=>logDose(state,key,'taken',at('08:40')),/already recorded/);
const prn={...med,id:'prn',times:[],mode:'list'};state.meds.push(prn);
logAsNeeded(state,'prn','unscheduled|1',at('09:00'),{takenAt:+at('08:40')});
assert.equal(lastTaken(state,'prn').takenAt,+at('08:40'));
assert.throws(()=>logAsNeeded(state,'prn','unscheduled|2',at('09:00'),{takenAt:+at('12:00')}),/future|past/);
state.meds.push({...prn,id:'justlist',listOnly:true});
assert.throws(()=>logAsNeeded(state,'justlist','unscheduled|3',at('09:00')));
const restored=readBackup(exportBackup(state));assert.deepEqual(restored,state);
const interval={...med,mode:'interval',times:['08:00'],anchorAt:+at('08:00'),untilAt:null,intervalHours:4};
const mixed=revisePlan(state,med,interval,next,day);
assert.deepEqual(dosesFor([mixed],next).map(r=>r.time),['00:00','04:00','08:00','12:00','16:00','20:00']);
assert.equal(scheduledPlans([mixed])[1].anchorAt,+new Date(next+'T00:00:00'));
console.log('Schedule changes, duplicate reminder suppression, actual time, caregiver attribution, PRN and backup tests passed.');
